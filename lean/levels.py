"""Builds reference-dag.md from the reference proofs: `python3 levels.py`.

Runs Reference/DAG.lean to get, for each reference theorem, the reference theorems its proof uses;
computes each theorem's depth (1 + the deepest theorem it uses); and writes a table. Definitional
lemmas proved by `rfl` count as depth 0, since the trivial-result screen would reject them.
"""
import re
import subprocess
from pathlib import Path

here = Path(__file__).parent
out = subprocess.run(['lake', 'env', 'lean', 'Reference/DAG.lean'], cwd=here, capture_output=True, text=True, check=True).stdout
deps = {}
for line in out.strip().splitlines():
    name, _, used = line.strip().partition(' <-')
    deps[name.removeprefix('OSO.')] = [d.strip().removeprefix('OSO.') for d in used.split(',') if d.strip()]

trivial = {'u_succ_succ'}
depth = {}
def d(n):
    if n not in depth:
        depth[n] = 1 + max((d(x) for x in deps[n] if x not in trivial), default=0)
    return depth[n]

area_of = {}
for f, area in [('A', 'A'), ('B', 'B'), ('C', 'C'), ('Cross', 'cross')]:
    for m in re.finditer(r'^theorem (\S+)', (here / 'Reference' / f'{f}.lean').read_text(), re.M):
        name = m.group(1)
        area_of['M2.' + name if f == 'C' else name] = area

checks = dict(re.findall(r'theorem check_(\w+) : target_\w+ := (?:fun [^⟩]*⟨)?(\w+)', (here / 'Reference' / 'Check.lean').read_text()))
posted = {v: k for k, v in checks.items()}
posted.update({'cnt_isort': 'B3'})  # B3 is the pair isort_sorted + cnt_isort
posted = {('M2.' + k if k in ('det_mul', 'pow_mul') else k): v for k, v in posted.items()}

rows = sorted((n for n in deps if n not in trivial), key=lambda n: (d(n), area_of.get(n, ''), n))
lines = [
    '# Reference lemma DAG',
    '',
    'Generated by `python3 levels.py` from the reference proofs. **Depth** is 1 + the deepest reference theorem a proof uses.',
    'Posted targets are marked with their id; every other theorem is a hidden reference lemma that agents have to find themselves.',
    '',
    '| Depth | Theorem | Area | Posted | Uses |',
    '| --- | --- | --- | --- | --- |',
]
for n in rows:
    uses = ', '.join(f'`{x}`' for x in deps[n] if x not in trivial) or '—'
    lines.append(f'| {d(n)} | `{n}` | {area_of.get(n, "?")} | {posted.get(n, "")} | {uses} |')
lines += ['', f'{len(rows)} theorems; maximum depth {max(d(n) for n in rows)}.', '']
(here / 'reference-dag.md').write_text('\n'.join(lines))
print('\n'.join(lines))
