"""Builds reference-dag.md from the reference proofs: `python3 levels.py`; the bigger set's
reference-dag-big.md: `python3 levels.py big`; the deep set's reference-dag-deep.md: `python3 levels.py deep`;
the QR set's reference-dag-qr.md (git-ignored while QR runs go on): `python3 levels.py qr`.

Runs Reference/DAG.lean to get, for each reference theorem, the reference theorems its proof uses;
computes each theorem's depth (1 + the deepest theorem it uses); and writes a table. Definitional
lemmas proved by `rfl` count as depth 0, since the trivial-result screen would reject them.
"""
import re
import subprocess
import sys
from pathlib import Path

here = Path(__file__).parent
big = sys.argv[1:] == ['big']
qr = sys.argv[1:] == ['qr']
deep = sys.argv[1:] == ['deep'] or qr
out = subprocess.run(['lake', 'env', 'lean', 'Reference/QRDAG.lean' if qr else 'Reference/DeepDAG.lean' if deep else 'Reference/BigDAG.lean' if big else 'Reference/DAG.lean'], cwd=here, capture_output=True, text=True, check=True).stdout
deps = {}
for line in out.strip().splitlines():
    name, _, used = line.strip().partition(' <-')
    deps[name.removeprefix('OSO.')] = [d.strip().removeprefix('OSO.') for d in used.split(',') if d.strip()]

trivial = {'u_succ_succ', 'L_succ_succ', 'L_one', 'v_eq_L'}
if deep:  # definitional lemmas, free to cite
    trivial = {'zero_eq', 'one_eq', 'add_zero', 'add_succ', 'mul_zero', 'mul_succ', 'pow_zero', 'pow_succ', 'succ_eq_add_one',
               'le_iff', 'lt_iff', 'dvd_iff', 'sum_zero', 'sum_succ', 'choose_zero_succ', 'choose_succ_succ'}
if qr:
    trivial |= {'mod_zero_left', 'mod_succ', 'div_zero_left', 'div_succ', 'prod_zero', 'prod_succ', 'count_zero', 'count_succ'}
depth = {}
def d(n):
    if n not in depth:
        depth[n] = 1 + max((d(x) for x in deps[n] if x not in trivial), default=0)
    return depth[n]

area_of = {}
for f, area in [('Deep', 'P')] if deep else [('A', 'A'), ('B', 'B'), ('C', 'C'), ('Cross', 'cross')] + ([('BigA', 'A'), ('BigAC', 'cross'), ('BigDE', 'D')] if big else []):
    for m in re.finditer(r'^theorem (\S+)', (here / 'Reference' / f'{f}.lean').read_text(), re.M):
        name = m.group(1)
        area_of['M2.' + name if f == 'C' else name] = area
area_of['isort_correct'] = 'B'
stage_of = {}
if qr:  # stage of each QR theorem, from the `## S<n>.` headers in QR.lean
    stage = 'S?'
    for line in (here / 'Reference' / 'QR.lean').read_text().splitlines():
        if m := re.match(r'/-! ## (S\d)', line):
            stage = m.group(1)
        elif m := re.match(r'theorem (\S+)', line):
            area_of[m.group(1)] = 'Q'
            stage_of[m.group(1)] = stage

checks = {} if deep else dict(re.findall(r'theorem check_(\w+) : target_\w+ := (?:fun [^⟩]*⟨)?(\w+)', (here / 'Reference' / 'Check.lean').read_text()))
if deep:
    checks.update(re.findall(r'theorem check_(\w+) : target_\w+ := (?:fun [^=]*=> )?(\w+)', (here / 'Reference' / ('QRCheck.lean' if qr else 'DeepCheck.lean')).read_text()))
if big:
    checks.update(re.findall(r'theorem check_(\w+) : target_\w+ := (?:fun [^=]*=> )?(\w+)', (here / 'Reference' / 'BigCheck.lean').read_text()))
posted = {v: k for k, v in checks.items()}
if big:  # the bigger set posts B3 on one theorem, the whole statement
    posted = {v: k for v, k in posted.items() if k != 'B3'}
    posted['isort_correct'] = posted.pop('isort_correct').removesuffix('_full')
elif not deep:
    posted.update({'cnt_isort': 'B3'})  # B3 is the pair isort_sorted + cnt_isort
posted = {('M2.' + k if k in ('det_mul', 'pow_mul', 'det_pow') else k): v for k, v in posted.items()}

if qr:  # only what the law rests on
    keep, todo = set(), list(posted)
    while todo:
        n = todo.pop()
        if n not in keep:
            keep.add(n); todo += deps[n]
    deps = {n: v for n, v in deps.items() if n in keep}
rows = sorted((n for n in deps if n not in trivial), key=lambda n: (d(n), area_of.get(n, ''), n))
lines = [
    '# Reference lemma DAG' + (', bigger set' if big else ', QR set (Peano to quadratic reciprocity)' if qr else ', deep set (Peano to Fermat)' if deep else ''),
    '',
    'Generated by `python3 levels.py` from the reference proofs. **Depth** is 1 + the deepest reference theorem a proof uses.',
    'Posted targets are marked with their id; every other theorem is a hidden reference lemma that agents have to find themselves.',
    *(['Area: P = the deep set\'s lemmas (Peano to Fermat) that the law uses; Q = the QR lemmas (their stages are listed at the end).'] if qr else []),
    '',
    '| Depth | Theorem | Area | Posted | Uses |',
    '| --- | --- | --- | --- | --- |',
]
for n in rows:
    uses = ', '.join(f'`{x}`' for x in deps[n] if x not in trivial) or '—'
    lines.append(f'| {d(n)} | `{n}` | {area_of.get(n, "?")} | {posted.get(n, "")} | {uses} |')
lines += ['', f'{len(rows)} theorems; maximum depth {max(d(n) for n in rows)}.', '']
if big:
    # Hubs: hidden lemmas that several posted targets rest on (directly or through other lemmas).
    def below(n, seen=None):
        seen = set() if seen is None else seen
        for x in deps[n]:
            if x not in seen and x not in trivial:
                seen.add(x); below(x, seen)
        return seen
    serves = {n: sorted({posted[t] for t in posted if n in below(t)}) for n in rows if n not in posted}
    hubs = sorted(((len(v), n, v) for n, v in serves.items() if len(v) >= 3), reverse=True)
    lines += ['## Hubs', '', 'Hidden lemmas that at least 3 posted targets rest on.', '', '| Lemma | Targets | Which |', '| --- | --- | --- |']
    lines += [f'| `{n}` | {k} | {", ".join(v)} |' for k, n, v in hubs] + ['']
if qr:
    names = {'S1': 'remainders and congruences', 'S2': 'products, and reordering them', 'S3': 'pairing, Wilson, Euler\'s criterion',
             'S4': 'Gauss\'s lemma', 'S5': 'parities, Eisenstein, the lattice count', 'S6': 'the law'}
    lines += ['## Stages', '', '| Stage | What | Steps | Depths |', '| --- | --- | --- | --- |']
    for st, what in names.items():
        ds = [d(n) for n in rows if stage_of.get(n) == st]
        lines.append(f'| {st} | {what} | {len(ds)} | {min(ds)}–{max(ds)} |')
    lines.append(f'| P | the deep set\'s lemmas | {sum(area_of.get(n) == "P" for n in rows)} | |')
    lines.append('')
(here / ('reference-dag-qr.md' if qr else 'reference-dag-deep.md' if deep else 'reference-dag-big.md' if big else 'reference-dag.md')).write_text('\n'.join(lines))
print('\n'.join(lines))
